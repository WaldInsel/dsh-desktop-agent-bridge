import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import assert from 'node:assert/strict';

// Bundle dependencies keep their license text even when users install only dist/.
export async function writeLicenseNotices(metafiles) {
  const packages = new Set();
  for (const metadata of metafiles) {
    for (const input of Object.keys(metadata.inputs)) {
      const match = /^node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input.replaceAll('\\', '/'));
      if (match) packages.add(match[1]);
    }
  }
  const notices = ['Third-party licenses for bundled dependencies\nGenerated by scripts/build.mjs.\n'];
  for (const name of [...packages].sort()) {
    const directory = join('node_modules', name);
    const metadata = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
    const files = (await readdir(directory)).filter(file => /^(license|licence|copying|notice)(\..*)?$/i.test(file));
    assert(files.length, `Missing bundled dependency license: ${name}`);
    notices.push(`\n${'='.repeat(72)}\n${name}@${metadata.version} (${metadata.license ?? 'see below'})\n`);
    for (const file of files.sort()) notices.push(await readFile(join(directory, file), 'utf8'));
  }
  await writeFile('dist/THIRD_PARTY_LICENSES.txt', notices.join('\n') + '\n');
}
